// =====================================================================
// THE WAYWARD COMPANY — MAP KNOWLEDGE TRACKER (per-bucket)
// ---------------------------------------------------------------------
// Firebase-synced binary reveal state, tracked per bucket:
//   0 — Unknown  (hidden on player site)
//   1 — Known    (visible on player site)
//
// Buckets: 'party' (shared) + one per PC ('sylas', 'torren', 'orin').
// Effective level for a PC = max(party, PC-specific).
//
// Firebase path /map-knowledge:
//   { <bucketId>: { <mapId>: 0|1 } }
//
// Data catalog comes from data/maps.json (generated by
// tools/generate_maps.py from the vault Maps/ folder). This module only
// tracks state; content comes from the catalog.
// =====================================================================
(function() {
  'use strict';

  const PATH = 'map-knowledge';
  const BUCKETS = ['party', 'sylas', 'torren', 'orin'];
  const BUCKET_LABELS = { party: 'Party (shared)', sylas: 'Sylas', torren: 'Torren', orin: 'Orin' };

  const MK = {
    _ref: null,
    _state: {},          // { bucketId: { mapId: 0|1 } }
    _catalog: [],        // loaded from data/maps.json
    _catalogLoaded: false,
    _dmBucket: 'party',
    _subs: [],

    init: function() {
      const self = this;
      this._loadCatalog();
      if (typeof firebase === 'undefined' || !firebase.database) {
        this._state = this._empty();
        this._fire();
        return;
      }
      try {
        this._ref = firebase.database().ref(PATH);
        this._ref.on('value', function(snap) {
          const v = snap.val();
          self._state = self._normalise(v);
          self._fire();
        });
      } catch (e) { console.warn('[MapKnowledge] Sync failed:', e); }
    },

    _loadCatalog: function(force) {
      const self = this;
      fetch('data/maps.json?t=' + Date.now(), { cache: 'no-store' })
        .then(function(r) { return r.ok ? r.json() : []; })
        .then(function(data) {
          self._catalog = Array.isArray(data) ? data : [];
          self._catalogLoaded = true;
          self._fire();
        })
        .catch(function(e) { console.warn('[MapKnowledge] Catalog fetch failed:', e); self._catalogLoaded = true; self._fire(); });
    },

    _empty: function() {
      const out = {};
      BUCKETS.forEach(function(b) { out[b] = {}; });
      return out;
    },

    _normalise: function(raw) {
      const out = this._empty();
      if (!raw || typeof raw !== 'object') return out;
      BUCKETS.forEach(function(b) {
        if (raw[b] && typeof raw[b] === 'object') {
          Object.keys(raw[b]).forEach(function(id) {
            out[b][id] = raw[b][id] ? 1 : 0;
          });
        }
      });
      return out;
    },

    subscribe: function(cb) {
      if (typeof cb !== 'function') return;
      this._subs.push(cb);
      try { cb(this._state); } catch (e) {}
    },

    _fire: function() {
      const self = this;
      this._subs.forEach(function(cb) { try { cb(self._state); } catch (e) {} });
    },

    getBucketLevel: function(bucketId, mapId) {
      const b = this._state[bucketId];
      return (b && b[mapId]) ? 1 : 0;
    },

    getEffectiveLevel: function(pcId, mapId) {
      const p = this.getBucketLevel('party', mapId);
      const s = pcId ? this.getBucketLevel(pcId, mapId) : 0;
      return Math.max(p, s);
    },

    setBucketLevel: function(bucketId, mapId, level) {
      const n = level ? 1 : 0;
      if (!this._ref) {
        if (!this._state[bucketId]) this._state[bucketId] = {};
        this._state[bucketId][mapId] = n;
        this._fire();
        return;
      }
      this._ref.child(bucketId).child(mapId).set(n).catch(function(e) { console.warn('[MapKnowledge] Write failed:', e); });
    },

    toggleBucketLevel: function(bucketId, mapId) {
      this.setBucketLevel(bucketId, mapId, this.getBucketLevel(bucketId, mapId) ? 0 : 1);
    },

    setAllInBucket: function(bucketId, level) {
      const self = this;
      this._catalog.forEach(function(m) { self.setBucketLevel(bucketId, m.id, level); });
    },

    getMap: function(mapId) {
      return this._catalog.find(function(m) { return m.id === mapId; });
    },

    openMap: function(mapId) {
      const m = this.getMap(mapId);
      if (!m) return;
      if (m.page) {
        window.open(m.page, '_blank', 'noopener');
      } else if (m.image) {
        _openImageOverlay(m);
      } else {
        _openInfoOverlay(m);
      }
    },

    // -------- DM view --------
    renderDM: function(containerId) {
      const container = document.getElementById(containerId);
      if (!container) return;
      const self = this;

      function paint() {
        if (!self._catalogLoaded) {
          container.innerHTML = '<div style="padding:1.5rem;text-align:center;color:var(--parch3);font-style:italic">Loading maps catalog…</div>';
          return;
        }
        if (!self._catalog.length) {
          container.innerHTML = '<div class="alert alert-warn">No maps found. Add files to the vault <code>Maps/</code> folder and run <code>python3 tools/regenerate_all.py</code>.</div>';
          return;
        }
        const bucket = self._dmBucket;
        let html = '';
        html += '<div style="display:flex;gap:.35rem;flex-wrap:wrap;margin-bottom:.5rem;align-items:center">' +
          '<span style="font-family:\'Cinzel\',serif;font-size:10px;color:var(--parch3);letter-spacing:1.5px;margin-right:.3rem">EDITING:</span>';
        BUCKETS.forEach(function(b) {
          const active = (b === bucket);
          html += '<button class="action-btn' + (active ? ' active' : '') + '" onclick="if(window.MapKnowledge){MapKnowledge._dmBucket=\'' + b + '\';MapKnowledge.renderDM(\'' + containerId + '\');}" style="' +
            (active ? 'background:var(--gold);color:#0d0a06;border-color:var(--gold)' : '') + '">' + BUCKET_LABELS[b] + '</button>';
        });
        html += '<button class="action-btn" style="margin-left:auto" onclick="if(window.MapKnowledge){MapKnowledge._loadCatalog();MapKnowledge.renderDM(\'' + containerId + '\');}" title="Re-fetch data/maps.json">🔄 Refresh catalog</button>';
        html += '</div>';

        html += '<div class="alert alert-info" style="margin-bottom:.5rem">' +
          (bucket === 'party'
            ? 'Party knowledge — click a map to toggle <strong>Unknown ↔ Known</strong>. When Known, the map appears on the player site.'
            : '<strong>' + BUCKET_LABELS[bucket] + '</strong> knows this <em>in addition to</em> what the whole party knows. Effective visibility per PC = max(party, PC).') +
          '</div>';

        // Group by region
        const regions = {};
        self._catalog.forEach(function(m) {
          const r = m.region || 'Other';
          if (!regions[r]) regions[r] = [];
          regions[r].push(m);
        });
        Object.keys(regions).sort().forEach(function(region) {
          html += '<div class="sec-title" style="margin-top:.6rem">' + _esc(region) + '</div>';
          html += '<div style="display:grid;grid-template-columns:repeat(auto-fill,minmax(240px,1fr));gap:.5rem;margin-bottom:.4rem">';
          regions[region].forEach(function(m) {
            const own = self.getBucketLevel(bucket, m.id);
            const partyLvl = self.getBucketLevel('party', m.id);
            const effective = Math.max(partyLvl, own);
            const isKnown = effective >= 1;
            const stateColor = own ? '#7fdb7f' : '#a08050';
            const stateLabel = own ? 'Known' : 'Unknown';
            const overrideNote = (bucket !== 'party' && own > partyLvl)
              ? '<div style="font-size:9px;color:var(--parch4);margin-top:1px">party unknown → this PC known</div>'
              : (bucket !== 'party' && partyLvl >= 1)
                ? '<div style="font-size:9px;color:var(--parch4);margin-top:1px">inherits Known from party</div>'
                : '';
            const thumb = m.image
              ? '<div style="width:100%;aspect-ratio:16/9;background:#000 url(\'' + _esc(m.image) + '\') center/cover no-repeat;border-radius:2px;margin-bottom:.35rem"></div>'
              : '';
            html += '<div style="border:1px solid ' + (isKnown ? '#7fdb7f' : 'rgba(160,128,64,0.4)') + ';border-radius:3px;padding:.5rem .6rem;background:rgba(20,14,6,0.35);display:flex;flex-direction:column;gap:.25rem">' +
              thumb +
              '<div style="display:flex;justify-content:space-between;align-items:flex-start;gap:.4rem">' +
                '<div style="font-family:\'Cinzel\',serif;color:var(--gold2);font-size:12px;flex:1">' + _esc(m.title) + '</div>' +
                (m.page ? '<a href="' + _esc(m.page) + '" target="_blank" rel="noopener" class="action-btn" style="padding:2px 6px;font-size:9px" title="Open DM reference page">↗</a>' : '') +
              '</div>' +
              (m.summary ? '<div style="font-size:11.5px;color:var(--parch2);line-height:1.45;display:-webkit-box;-webkit-line-clamp:3;-webkit-box-orient:vertical;overflow:hidden">' + _esc(m.summary) + '</div>' : '') +
              '<div style="display:flex;justify-content:space-between;align-items:center;margin-top:.35rem;gap:.4rem">' +
                '<button class="action-btn" onclick="if(window.MapKnowledge) MapKnowledge.toggleBucketLevel(\'' + bucket + '\',\'' + m.id + '\')" style="padding:3px 8px;font-size:10px;background:' + stateColor + '22;border-color:' + stateColor + ';color:' + stateColor + '">● ' + stateLabel + '</button>' +
                (m.image || (!m.image && !m.page) ? '<button class="action-btn" onclick="if(window.MapKnowledge) MapKnowledge.openMap(\'' + m.id + '\')" style="padding:3px 8px;font-size:10px">👁 View</button>' : '') +
              '</div>' +
              overrideNote +
            '</div>';
          });
          html += '</div>';
        });
        html += '<div style="display:flex;gap:.4rem;flex-wrap:wrap;margin-top:.75rem">' +
          '<button class="action-btn" onclick="if(window.MapKnowledge) MapKnowledge.setAllInBucket(\'' + bucket + '\',0)">Reset ' + BUCKET_LABELS[bucket] + ' → Unknown</button>' +
          '<button class="action-btn" onclick="if(window.MapKnowledge) MapKnowledge.setAllInBucket(\'' + bucket + '\',1)">→ All Known</button>' +
        '</div>';
        container.innerHTML = html;
      }
      this.subscribe(paint);
      paint();
    },

    // -------- Player view --------
    renderPlayer: function(containerId, identity) {
      const container = document.getElementById(containerId);
      if (!container) return;
      const self = this;
      const pcId = (identity && identity.id) || null;
      function paint() {
        if (!self._catalogLoaded) { container.innerHTML = '<div class="card-body" style="font-style:italic;color:var(--ink3)">Loading…</div>'; return; }
        const visible = self._catalog.filter(function(m) { return self.getEffectiveLevel(pcId, m.id) >= 1; });
        if (!visible.length) {
          container.innerHTML = '<div class="card-body" style="color:var(--ink3);font-style:italic">You have not yet visited or been shown any maps of note.</div>';
          return;
        }
        let html = '<div style="display:grid;grid-template-columns:repeat(auto-fill,minmax(240px,1fr));gap:.5rem">';
        visible.forEach(function(m) {
          const thumb = m.image
            ? '<div style="width:100%;aspect-ratio:16/9;background:#000 url(\'' + _esc(m.image) + '\') center/cover no-repeat;border-radius:2px;margin-bottom:.35rem"></div>'
            : '';
          html += '<div class="card" style="cursor:pointer" onclick="if(window.MapKnowledge) MapKnowledge.openMap(\'' + m.id + '\')">' +
            thumb +
            '<div class="card-title">' + _esc(m.title) + '</div>' +
            (m.region ? '<div class="card-sub">' + _esc(m.region) + '</div>' : '') +
            (m.summary ? '<div class="card-body" style="font-size:12px">' + _esc(m.summary) + '</div>' : '') +
          '</div>';
        });
        html += '</div>';
        container.innerHTML = html;
      }
      this.subscribe(paint);
      paint();
    }
  };

  function _esc(s) {
    return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  function _openImageOverlay(m) {
    let overlay = document.getElementById('map-image-overlay');
    if (!overlay) {
      overlay = document.createElement('div');
      overlay.id = 'map-image-overlay';
      overlay.style.cssText = 'position:fixed;inset:0;background:rgba(5,3,2,0.92);z-index:2147483646;display:none;align-items:center;justify-content:center;padding:1rem;flex-direction:column;gap:.75rem';
      overlay.innerHTML =
        '<div style="display:flex;gap:.5rem;align-items:center">' +
          '<div id="map-image-title" style="font-family:\'Cinzel\',serif;color:var(--gold2,#c9a84c);font-size:13px;letter-spacing:1.5px"></div>' +
          '<button class="action-btn" onclick="document.getElementById(\'map-image-overlay\').style.display=\'none\'" style="padding:3px 10px">✕ Close</button>' +
        '</div>' +
        '<img id="map-image-el" style="max-width:min(95vw,1600px);max-height:calc(100vh - 90px);object-fit:contain;border:1px solid var(--gold2,#c9a84c);border-radius:4px;background:#000">';
      document.body.appendChild(overlay);
      overlay.addEventListener('click', function(e) { if (e.target === overlay) overlay.style.display = 'none'; });
      document.addEventListener('keydown', function(e) { if (e.key === 'Escape' && overlay.style.display === 'flex') overlay.style.display = 'none'; });
    }
    document.getElementById('map-image-title').textContent = m.title;
    document.getElementById('map-image-el').src = m.image;
    overlay.style.display = 'flex';
  }

  function _openInfoOverlay(m) {
    // Info-only fallback (no image and no page) — use the same faction-dialog pattern
    let dlg = document.getElementById('faction-dialog');
    if (!dlg) return;
    document.getElementById('faction-dialog-title').textContent = m.title;
    document.getElementById('faction-dialog-source').textContent = m.sourceFile || '';
    document.getElementById('faction-dialog-body').innerHTML = m.html || '';
    if (dlg.showModal) dlg.showModal(); else dlg.setAttribute('open', '');
  }

  window.MapKnowledge = MK;

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function() { setTimeout(function() { MK.init(); }, 200); });
  } else {
    setTimeout(function() { MK.init(); }, 200);
  }
})();
